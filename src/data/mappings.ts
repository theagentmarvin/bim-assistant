export interface LoadedMappings {
  mappings: Mapping[];
  source: "presets" | "placeholder";
  run: MappingPresets["run"] | null;
}

export function loadMappings(): LoadedMappings {
  try {
    const data = asMappingPresets(presetsRaw);
    if (data && Array.isArray(data.mappings) && data.mappings.length > 0) {
      return { mappings: data.mappings, source: "presets", run: data.run };
    }
  } catch (err) {
    // eslint-disable-next-line no-console
    console.warn(
      "[mappings] Failed to load mapping_presets.json, using placeholders:",
      err,
    );
  }
  return { mappings: placeholderMappings(), source: "placeholder", run: null };
}