// Data loader for mapping_presets.json.
//
// Strategy:
//   1. Static import the JSON. Vite resolves the relative path at build time
//      and bundles the file. Works for both `npm run dev` and `npm run build`.
//   2. If the import fails (e.g. data file missing in CI / fresh checkout),
//      fall back to 20 hardcoded placeholder sections so the UI still renders.
//
// Path math:
//   This file: src/ui/src/data/mappings.ts
//   Target:    <project>/data/processed/validation/mapping_presets.json
//   Rel:       ../../data/mapping_presets.json

import type { Mapping, MappingPresets, Pass } from "../types";

import presetsRaw from "../../data/mapping_presets.json";

function asMappingPresets(raw: unknown): MappingPresets {
  // Cast through unknown — the JSON is generated by our own mapper script and
  // already conforms to the schema. Trust the source, but keep the boundary
  // explicit so TS catches downstream changes to types.ts.
  return raw as unknown as MappingPresets;
}

